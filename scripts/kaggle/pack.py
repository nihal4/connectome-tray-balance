"""Pack a Kaggle GPU job: one self-contained script (run.py) + kernel-metadata.json, ready for
`kaggle kernels push -p OUT`.  Used by `fly kaggle ...`; you normally do not call it yourself.

Security: only an allow-list of code files is packed (never .env files, keys, runs or logs), the result is
scanned for the Kaggle key and for anything that looks like an API key before it is written, and the
notebook is private.  The job itself needs no key: it installs its packages and downloads the public Panda
model from GitHub, then writes its report to /kaggle/working.

    python scripts/kaggle/pack.py --job mjx --user NAME --out DIR [--args "--batches 64,256"]
"""
import argparse
import base64
import glob
import io
import json
import os
import re
import subprocess
import sys
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

JOBS = {   # job -> (script to run on Kaggle, extra pip packages, title)
    "mjx": ("scripts/kaggle/mjx_feasibility.py", ["jax[cuda12]", "mujoco-mjx=={mj}", "gymnasium", "scipy"],
            "flybrain-mjx"),
}
ALLOW = ["ctb/**/*.py", "ctb/envs/*.xml", "scripts/__init__.py", "scripts/download_panda.py", "scripts/kaggle/*.py",
         "data/smell_door.npz"]
SECRET_PATTERNS = [re.compile(rb"KGAT_[A-Za-z0-9_\-]{10,}"),                   # Kaggle API token
                   re.compile(rb"\"key\"\s*:\s*\"[0-9a-f]{32}\""),             # kaggle.json
                   re.compile(rb"(?i)(api[_-]?key|secret|password|token)\s*=\s*['\"][^'\"\s]{12,}['\"]"),
                   re.compile(rb"gh[pousr]_[A-Za-z0-9]{30,}"),                 # GitHub tokens
                   re.compile(rb"sk-[A-Za-z0-9_\-]{20,}")]                     # other API keys

RUNNER = '''# Auto-generated by scripts/kaggle/pack.py (job "{job}", code from commit {sha}). Contains no keys.
import base64, io, os, subprocess, sys, tarfile
PAYLOAD = "{payload}"
SRC = "/kaggle/temp/flybrain" if os.path.isdir("/kaggle") else "/tmp/flybrain"
OUT = "/kaggle/working/{job}_report" if os.path.isdir("/kaggle/working") else "{job}_report"


def sh(cmd, check=True):
    print("$", cmd, flush=True)
    return subprocess.run(cmd, shell=True, check=check)


os.makedirs(SRC, exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz") as tf:
    try:
        tf.extractall(SRC, filter="data")
    except TypeError:
        tf.extractall(SRC)
sh(f"{{sys.executable}} -m pip install -q {pip}")
sh(f"cd {{SRC}} && {{sys.executable}} scripts/download_panda.py")
sh("nvidia-smi --query-gpu=name,memory.total --format=csv", check=False)
sh(f"cd {{SRC}} && {{sys.executable}} -u {script} --out {{OUT}} {args}")
'''


def secret_values():
    return [v.encode() for k, v in os.environ.items()
            if k in ("KAGGLE_KEY", "KAGGLE_API_TOKEN") and len(v) >= 8]


def scan(name, data, values):
    for v in values:
        if v in data:
            sys.exit(f"STOP: {name} contains your Kaggle key. Nothing was written or pushed.")
    for p in SECRET_PATTERNS:
        if p.search(data):
            sys.exit(f"STOP: {name} contains something that looks like an API key ({p.pattern[:30]!r}). "
                     f"Nothing was written or pushed.")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--job", required=True, choices=sorted(JOBS))
    ap.add_argument("--user", required=True, help="Kaggle username (the notebook's owner)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--args", default="", help="extra arguments for the job's script")
    a = ap.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9_\-]+", a.user):
        sys.exit("bad Kaggle username")
    if not re.fullmatch(r"[A-Za-z0-9_,.=\- ]*", a.args):
        sys.exit("job arguments may only contain letters, digits and , . = - _ (nothing else is needed)")
    import mujoco
    script, pip, title = JOBS[a.job]
    pip = " ".join(f"'{p.format(mj=mujoco.__version__)}'" for p in [f"mujoco=={mujoco.__version__}"] + pip)
    values = secret_values()

    files = sorted({f for pat in ALLOW for f in glob.glob(os.path.join(ROOT, pat), recursive=True)})
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        for f in files:
            rel = os.path.relpath(f, ROOT)
            with open(f, "rb") as fh:
                scan(rel, fh.read(), values)
            tf.add(f, arcname=rel)
    try:
        sha = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True,
                             text=True).stdout.strip() or "unknown"
    except OSError:
        sha = "unknown"
    run = RUNNER.format(job=a.job, sha=sha, payload=base64.b64encode(buf.getvalue()).decode(), pip=pip,
                        script=script, args=a.args)
    meta = {"id": f"{a.user}/{title}", "title": title, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
            "enable_internet": "true", "machine_shape": "NvidiaTeslaT4", "dataset_sources": [],
            "competition_sources": [], "kernel_sources": [], "model_sources": []}
    scan("run.py", run.encode(), values)
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "run.py"), "w") as f:
        f.write(run)
    with open(os.path.join(a.out, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(f"packed {len(files)} files ({len(run) // 1024} kB, commit {sha}) -> {a.out}  "
          f"[private notebook {meta['id']}, T4 GPU, scanned: no keys]")


if __name__ == "__main__":
    main()
